import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { compatibilityStatusLabels, filterCompatibilityEntries, getCompatibilitySummary } from "../lib/game-compatibility.mjs";

export function renderCompatibilityDocs(data) {
  const summary = getCompatibilitySummary(data.entries);
  const date = new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(data.recordedOn));
  const cell = (text) => text.replaceAll("|", "\\|");
  const tested = filterCompatibilityEntries(data.entries, { status: "startup-verified" });
  const warnings = filterCompatibilityEntries(data.entries, { status: "startup-warning" });
  const failed = filterCompatibilityEntries(data.entries, { status: "startup-failed" });
  const untested = filterCompatibilityEntries(data.entries, { status: "not-tested" });
  const checkedTable = (entries) => `| Game | Checked edition | Game ID | Observation |
| --- | --- | --- | --- |
${entries.map((entry) => {
    const previous = (entry.history ?? []).slice(0, -1).map((check) =>
      ` Earlier check (${check.recordedOn}): ${compatibilityStatusLabels[check.status]} — ${check.observation}`
    ).join("");
    return `| ${cell(entry.title)} | ${cell(entry.edition.replace(/\.zip$/i, ""))} | \`${entry.gameId}\` | ${cell(entry.observation + previous)} |`;
  }).join("\n")}`;
  return `# Game testing

<!-- Generated by scripts/generate-compatibility-docs.mjs. Edit data/game-compatibility.json. -->

Status recorded on **${date}**. Open **Game compatibility** from the checklist icon
in the top bar to search these results and inspect checked editions.

| Status | Games | Editions |
| --- | ---: | ---: |
| [Tested: startup verified](#tested-startup-verified) | ${summary.verifiedGames} | ${summary.verified} |
| [Startup with warnings](#startup-with-warnings) | ${new Set(warnings.map((entry) => entry.title)).size} | ${summary.warnings} |
| [Startup failed](#startup-failed) | ${new Set(failed.map((entry) => entry.title)).size} | ${summary.failed} |
| [Not yet tested](#not-yet-tested) | ${summary.untested} | — |

**Tested** means the game reached a startup screen, menu, or first game scene.
It does not establish full-game compatibility or confirm every feature.
Warnings describe workarounds, audio limitations, or original game prompts.
Failures are checked editions that stopped before startup. Games can have
editions in more than one status; ${summary.checked} editions have been checked.
The [compatibility data](../data/game-compatibility.json) is the source of truth
for this page and the in-app modal, including all checked editions.

## Tested: startup verified

${data.notes[0]}
${data.notes[1]}

${checkedTable(tested)}

## Startup with warnings

These editions reached a startup screen or original game prompt with the limitations below.

${checkedTable(warnings)}

## Startup failed

${failed.length ? checkedTable(failed) : "No recorded startup failures remain for the checked editions."}

## Not yet tested

These games have no recorded ScummWEB test result. Ratings come from the
[ScummVM ${data.upstreamReference.version} compatibility chart](${data.upstreamReference.url}).
${data.upstreamReference.scope}

${data.notes[2]}

| Game | Reference game ID | Upstream ScummVM rating |
| --- | --- | --- |
${untested.map((entry) => `| ${cell(entry.title)} | \`${entry.gameId}\` | ${entry.upstreamRating} |`).join("\n")}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = JSON.parse(await readFile(new URL("../data/game-compatibility.json", import.meta.url), "utf8"));
  const output = new URL("../docs/game-testing.md", import.meta.url);
  const markdown = renderCompatibilityDocs(data);
  if (process.argv.includes("--check")) {
    if (await readFile(output, "utf8") !== markdown) {
      throw new Error("Compatibility docs are stale. Run node scripts/generate-compatibility-docs.mjs.");
    }
  } else {
    await writeFile(output, markdown);
  }
}
